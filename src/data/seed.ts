// Week labels: months 8-12 belong to 2026, months 1-7 to 2027.
function weekToDate(label: string): Date {
  const [m, d] = label.split('/').map(Number)
  const year = m >= 8 ? 2026 : 2027
  return parseISO(`${year}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`)
}

export function buildSeedIssues(): IssueInput[] {
  const issues: IssueInput[] = []
  for (const { track, items } of SEED) {
    for (const item of items) {
      const start = weekToDate(item.w)
      const weeks = item.n ?? 1
      const end = addDays(start, weeks * 7 - 1)
      issues.push({
        track,
        title: item.t,
        description: item.desc,
        status: 'todo',
        priority: item.p ?? 'medium',
        startDate: toISO(start),
        dueDate: toISO(end),
        deliverables: item.d.map((name) => ({ name, done: false })),
      })
    }
  }
  return issues
}
